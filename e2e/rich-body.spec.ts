// 本文の装飾（base の RichBody・RichInput・RichText）: 本文の入力Form は装飾を見たまま書き、上のボックスで選んだ範囲を太字・文字の色にし、箱に装飾して描く
import { expect, type Page, test } from "@playwright/test"
import { drawerTool } from "./drawer"
import { selectText } from "./rich"

async function onPaper(page: Page, x: number, y: number) {
  const paper = (await page.getByRole("img", { name: "紙" }).boundingBox())!
  return { x: paper.x + x, y: paper.y + y }
}

test("本文の上のボックスで、選んだ範囲を太字と注意の色にすると、記号は見せずに装飾して描き、箱でも太字・色で描く", async ({
  page,
}) => {
  await page.goto("/")
  await (await drawerTool(page, "箱")).click()
  const at = await onPaper(page, 200, 150)
  await page.mouse.click(at.x, at.y)
  const dialog = page.getByRole("dialog", { name: "ボックスの追加" })
  const body = dialog.getByLabel("本文", { exact: true })
  await body.fill("気をつける所")
  await selectText(body, 0, 3)
  const bar = dialog.getByRole("toolbar", { name: "本文の装飾" })
  await bar.getByRole("button", { name: "太字" }).click()
  await expect(body).toHaveText("気をつける所")
  await expect(body.locator("[data-bold]")).toHaveText("気をつ")
  await bar.getByRole("button", { name: "注意" }).click()
  await expect(body.locator('[data-bold][data-color="@matomezu/base:warn"]')).toHaveText("気をつ")
  await expect(body.locator("[data-bold]")).toHaveCSS("color", "rgb(217, 119, 6)")
  await dialog.getByRole("button", { name: "追加" }).click()
  const span = page.locator("[data-item] [data-line] span").first()
  await expect(span).toHaveText("気をつ")
  await expect(span).toHaveCSS("font-weight", "700")
  await expect(span).toHaveCSS("color", "rgb(217, 119, 6)")
  expect((await page.locator("[data-item] [data-line]").allTextContents()).join("")).toBe("気をつける所")
})

test("範囲を囲んだ色の中で色なしを押すと色が外れ、太字を押し直すと太字が外れる。範囲を選ばずに太字を押すと、次に書く字が太字", async ({
  page,
}) => {
  await page.goto("/")
  await (await drawerTool(page, "箱")).click()
  const at = await onPaper(page, 200, 150)
  await page.mouse.click(at.x, at.y)
  const dialog = page.getByRole("dialog", { name: "ボックスの追加" })
  const body = dialog.getByLabel("本文", { exact: true })
  const bar = dialog.getByRole("toolbar", { name: "本文の装飾" })
  await body.fill("メモ")
  await selectText(body, 0, 2)
  await bar.getByRole("button", { name: "情報" }).click()
  await expect(body.locator("[data-color]")).toHaveText("メモ")
  await bar.getByRole("button", { name: "色なし" }).click()
  await expect(body.locator("[data-color]")).toHaveCount(0)
  await bar.getByRole("button", { name: "太字" }).click()
  await expect(body.locator("[data-bold]")).toHaveText("メモ")
  await bar.getByRole("button", { name: "太字" }).click()
  await expect(body.locator("[data-bold]")).toHaveCount(0)
  await selectText(body, 2, 2)
  await bar.getByRole("button", { name: "太字" }).click()
  await page.keyboard.type("帳")
  await expect(body.locator("[data-bold]")).toHaveText("帳")
  await expect(body).toHaveText("メモ帳")
})

test("記号の字を打てばそのまま字として残り、箱でも装飾にならない。元に戻すで書く前に戻る", async ({ page }) => {
  await page.goto("/")
  await (await drawerTool(page, "箱")).click()
  const at = await onPaper(page, 200, 150)
  await page.mouse.click(at.x, at.y)
  const dialog = page.getByRole("dialog", { name: "ボックスの追加" })
  const body = dialog.getByLabel("本文", { exact: true })
  await body.click()
  await page.keyboard.type("x")
  await page.keyboard.press("ControlOrMeta+z")
  await expect(body).toHaveText("")
  await page.keyboard.type("**a**{warn:b}")
  await expect(body.locator("[data-bold], [data-color]")).toHaveCount(0)
  await dialog.getByRole("button", { name: "追加" }).click()
  expect((await page.locator("[data-item] [data-line]").allTextContents()).join("")).toBe("**a**{warn:b}")
  await expect(page.locator("[data-item] [data-line] span")).toHaveCount(0)
})

test("行の編集で書いた本文は、確定の前からリストの行に重ねて見せ、キャンセルでは元に戻る", async ({ page }) => {
  await page.goto("/")
  await (await drawerTool(page, "リスト")).click()
  const at = await onPaper(page, 120, 120)
  await page.mouse.click(at.x, at.y)
  const add = page.getByRole("dialog", { name: "リストの追加" })
  await add.getByLabel("キャプション", { exact: true }).fill("予定")
  await add.getByRole("button", { name: "追加" }).click()
  const list = page.locator("[data-item]", { hasText: "予定" })
  await list.getByRole("button", { name: "行の追加" }).click()
  const row = page.getByRole("dialog", { name: "行の追加" })
  await row.getByLabel("キャプション", { exact: true }).fill("会議")
  await row.getByRole("button", { name: "追加" }).click()
  await list.getByRole("listitem").first().dblclick()
  const edit = page.getByRole("dialog", { name: "行の編集" })
  const body = edit.getByLabel("本文", { exact: true })
  await body.fill("中止")
  await selectText(body, 0, 2)
  await edit.getByRole("toolbar", { name: "本文の装飾" }).getByRole("button", { name: "エラー" }).click()
  const span = list.getByRole("listitem").first().locator("span", { hasText: "中止" })
  await expect(span).toHaveCSS("color", "rgb(220, 38, 38)")
  await edit.getByRole("button", { name: "キャンセル" }).click()
  await expect(list.getByRole("listitem").first()).toHaveText("会議")
})

test("マスターの設定で文字の色を自分用に変えると、図面の本文のその色が変わる", async ({ page }) => {
  await page.goto("/")
  await (await drawerTool(page, "箱")).click()
  const at = await onPaper(page, 200, 150)
  await page.mouse.click(at.x, at.y)
  const add = page.getByRole("dialog", { name: "ボックスの追加" })
  const body = add.getByLabel("本文", { exact: true })
  await body.fill("注意")
  await selectText(body, 0, 2)
  await add.getByRole("toolbar", { name: "本文の装飾" }).getByRole("button", { name: "注意" }).click()
  await add.getByRole("button", { name: "追加" }).click()
  const span = page.locator("[data-item] [data-line] span").first()
  await expect(span).toHaveCSS("color", "rgb(217, 119, 6)")
  const trigger = page.locator('button[aria-haspopup="menu"]').first()
  await trigger.hover()
  await trigger.locator("xpath=../following-sibling::div[1]").getByRole("button", { name: "ホーム" }).click()
  const master = page.getByRole("region", { name: "マスター" })
  await master.getByRole("button", { name: "注意" }).click()
  const picker = page.getByRole("dialog", { name: "色を選ぶ" })
  await picker.getByLabel("色の値（#rrggbb）").fill("#7c3aed")
  await picker.getByLabel("色の値（#rrggbb）").press("Enter")
  await page.keyboard.press("Escape")
  await page.goBack()
  await expect(span).toHaveCSS("color", "rgb(124, 58, 237)")
})
